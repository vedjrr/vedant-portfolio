/** "VA" monogram drawn on a pixel grid, like the reference logo. */
export function Monogram(props: SVGProps<SVGSVGElement>) {
  // 11 x 7 grid. 1 = filled pixel.
  const rows = [
    "10001001110",
    "10001010001",
    "10001010001",
    "01010011111",
    "01010010001",
    "00100010001",
    "00100010001",
  ];
  return (
    <svg viewBox="0 0 11 7" fill="currentColor" aria-hidden="true" {...props}>
      {rows.flatMap((row, y) =>
        row
          .split("")
          .map((c, x) =>
            c === "1" ? (
              <rect key={`${x}-${y}`} x={x} y={y} width="1.02" height="1.02" />
            ) : null,
          ),
      )}
    </svg>
  );
}
